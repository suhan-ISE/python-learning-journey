# A while loop in Python repeatedly executes a block of code
#              as long as a specified condition remains True.

# initialize a count variable
count = 0
# condition count should be less than or equal to 5
while count <= 5:
    print(f"count is : {count}")
    count += 1            # count = count + 1

# once count is equal to 5 loop's break
print("loop is finished")